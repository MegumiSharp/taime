const _todoDetails = AndroidNotificationDetails(
  'todo',
  'Promemoria to-do',
  channelDescription: 'Scadenze della lista to-do',
  importance: Importance.high,
  priority: Priority.high,
  category: AndroidNotificationCategory.reminder,
);

Future<void> scheduleTodoReminder({
  required int todoId,
  required DateTime at,
  required String title,
  required String body,
}) async {
  await initTz();
  await plugin.cancel(id: kTodoIdBase + todoId);
  if (!at.isAfter(DateTime.now())) return;
  await _scheduleAlarm(
    id: kTodoIdBase + todoId,
    at: at,
    title: title,
    body: body,
    payload: 'todo:$todoId',
    details: const NotificationDetails(android: _todoDetails),
  );
}

Future<void> cancelTodoReminder(int todoId) => _cancel(kTodoIdBase + todoId);

